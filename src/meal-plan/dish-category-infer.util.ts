export type MealSlotKeyInfer = 'breakfast' | 'lunch' | 'dinner' | 'snack';

/**
 * Определение приёма пищи по названию блюда.
 *
 * Раньше функция возвращала `dinner` для всего, что не попало в узкий список
 * ключевых слов. Из-за этого в каталоге оказалось 406 «ужинов», 0 «обедов»
 * и всего 22 «завтрака», а генератор планов не мог подобрать обед
 * (пул `lunch` был пуст, и обед подставлялся из ужинов/закусок).
 *
 * Теперь порядок проверок — от наиболее специфичных к общим, а `lunch`
 * (основной приём пищи) покрывает супы, гарниры с мясом/рыбой, боулы и т. п.
 * Функция используется и при импорте каталога, и при переклассификации,
 * и в SQL-фильтрах генератора планов.
 */
export function inferMealSlotFromDishName(name: string): MealSlotKeyInfer {
  const n = String(name ?? '').toLowerCase().replace(/ё/g, 'е').trim();
  if (!n) return 'dinner';

  // 0. Алкогольные и безалкогольные НАПИТКИ — всегда перекус.
  //    Проверяем первым: иначе «Коктейль Абсолютно великолепный» попадал
  //    в категорию обеда (40 напитков из TheCocktailDB оказались в lunch).
  if (
    /(коктейл|мохито|маргарит|дайкири|сангрия|апероль|кампари|мартини|вермут|виски|водка|джин|ром(?![а-яё])|текила|абсент|ликер|ликёр|бренди|коньяк|кониак|шампан|просекко|игристое|сидр|пиво|эль(?![а-яё])|лагер|стаут|саке|глинтвейн|пунш|грог|настойка|бальзам|кальвадос|бурбон|скотч|шартрез|самбука|граппа|баилейс|бейлис|куантро|трипл сек|корона|вино(?![а-яё])|винн|шампанск|игристое|портвейн|херес|мадера|кагор|мускат|рислинг|мерло|каберне|шардоне|пивн|пиво(?![а-яё]))/i.test(
      n,
    ) ||
    /\b(cocktail|mocktail|mojito|margarita|daiquiri|sangria|martini|vermouth|whisk(e)?y|vodka|gin|rum|tequila|absinthe|liqueur|brandy|cognac|champagne|prosecco|cider|beer|ale|lager|stout|sake|mulled wine|punch|grog)\b/i.test(
      n,
    ) ||
    // Безалкогольные напитки
    /(сок\b|смузи|лимонад|морс|компот|кисель|квас|чай\b|кофе|какао|милкшейк|фраппе|латте|капучино|эспрессо|матча|smoothie|juice|lemonade|milkshake|frappe|latte|cappuccino|espresso|matcha|soda|кола\b)/i.test(
      n,
    )
  ) {
    return 'snack';
  }

  // 1. Завтраки — проверяем раньше остальных: «сырники», «омлет», «каша»
  //    иначе могут попасть в общие правила.
  if (
    /\b(breakfast|oatmeal|porridge|pancake|pancakes|waffle|waffles|toast|omelette|omelet|scrambled|french toast|granola|muesli|croissant|syrniki)\b/i.test(
      n,
    ) ||
    /завтрак|каша|овсян|овсяноблин|блин|блинчик|оладь|омлет|яичниц|гренк|тост|сырник|вафл|круассан|творожн(ая|ый) запекан|шакшук|драник|манн(ая|ой) каш|ленив(ые|ых) вареник|пудинг рисов|йогурт с/i.test(
      n,
    )
  ) {
    return 'breakfast';
  }

  // 2. Основное горячее с гарниром — проверяем ДО салатов/перекусов:
  //    «Курица Piri-piri с салатом» — это обед, а не перекус.
  if (
    /\b(pasta|spaghetti|lasagna|lasagne|risotto|pilaf|burrito|taco|quesadilla|burger|pizza|sandwich|wrap|curry|stew|roast|steak|casserole|gratin|chili|kebab|shawarma|ramen)\b/i.test(
      n,
    ) ||
    /паста|лапша|спагетти|макарон|феттучин|карбонар|болоньез|лазань|ризотто|плов|бургер|пицц|сэндвич|шаурм|шаверм|дёнер|донер|кебаб|карри|гуляш|фрикадель|тефтел|котлет|шницель|эскалоп|бефстроганов|пожарск|жаркое|чахохбил|сациви|аджапсандал|мусака|паэлья|кесадилья|суши|ролл\b|пельмен|вареник|манты|хинкал|чебурек|ригатони|пенне|фарфалле|тортеллини|равиоли/i.test(
      n,
    )
  ) {
    return 'lunch';
  }

  // 2b. Белковое горячее («Курица …», «Лосось …») — основной приём, даже если
  //     в названии есть слово «салат» (салат здесь гарнир, а не суть блюда).
  if (
    /^(куриц|курин|куриная|говядин|говяж|свинин|свиная|индейк|баранин|телятин|ягнен|лосос|треск|тунец|рыб[аи]|кревет|миди|кальмар|стейк|филе|ветчин|утк|кролик|тофу)/i.test(
      n,
    ) &&
    !/^салат/i.test(n)
  ) {
    return 'lunch';
  }

  // 3. Перекусы: десерты, напитки, лёгкие закуски, выпечка, фрукты/орехи.
  if (
    /\b(salad|smoothie|cake|cookies?|biscuit|dessert|snack|tea|coffee|juice|lemonade|sorbet|ice cream|brownie|muffin|cupcake|donut|doughnut|pudding|truffle|candy|chocolate|milkshake|frappe|sundae|parfait|cocktail|mocktail)\b/i.test(
      n,
    ) ||
    /салат|смузи|перекус|десерт|торт|пирожн|печенье|кекс|маффин|брауни|пончик|пудинг|мусс|желе|мороженое|сорбет|конфет|шоколад|козинак|халва|нуга|мармелад|зефир|пастил|варенье|джем|мёд\b|мед\b|йогурт|мусли|гранола|чипсы|сухарик|крекер|орешк|миндал|фундук|кешью|фисташк|арахис|семечк|батончик|компот|чай\b|кофе|какао|лимонад|морс|кисель|квас|фрукт|ягод|банан|яблоко|груш|апельсин|мандарин|виноград|арбуз|дын|персик|абрикос|слив|вишн|черешн|клубник|малин|черник|голубик|смородин|крыжовник|инжир|финик|изюм|кураг|чернослив|баклава|крамбл/i.test(
      n,
    )
  ) {
    return 'snack';
  }

  // 4. Обед: супы, боулы и прочие основные блюда, не попавшие в п.2.
  if (
    /\b(soup|broth|bowl|fillet|cutlet|dumpling|noodles|sushi|moussaka|paella)\b/i.test(n) ||
    /суп|борщ|бульон|солянк|похлеб|уха\b|окрошк|харчо|гаспачо|крем-суп|боул|рис\b|рис с|рис по|булгур|кускус|полба|перловк|ячнев|гречк|кур(а|иц|ин|ы)|говяд|говядин|свинин|индейк|баранин|телятин|ягнен|стейк|филе|запеканк|дал\b|чили|удон|соба|картофельное пюре|пюре с/i.test(
      n,
    )
  ) {
    return 'lunch';
  }

  // 4. Ужин — то, что не подошло выше: лёгкие горячие блюда, овощи, рыба.
  if (
    /\b(dinner|supper|grilled|baked|stuffed|vegetable|veggie|omelet)\b/i.test(n) ||
    /ужин|запечен|тушен|грил|овощ|рагу из овощ|баклажан|кабачок|цукини|брокколи|цветная капуст|спарж|шпинат|тыкв|свекл|морков|реп[ау]|редьк|редис|сельдерей|фенхел|артишок|тофу|темпе|гриб|шампиньон|вешенк/i.test(
      n,
    )
  ) {
    return 'dinner';
  }

  // 5. Не опознали — считаем основным блюдом (обед), а не ужином:
  //    это безопаснее, чем сваливать всё в один слот.
  return 'lunch';
}

export function dishStoredOrInferredMatchesSlot(
  storedCategory: string,
  dishName: string,
  slot: MealSlotKeyInfer,
): boolean {
  const s = String(storedCategory ?? '').toLowerCase();
  if (s === slot) return true;
  return inferMealSlotFromDishName(dishName) === slot;
}
