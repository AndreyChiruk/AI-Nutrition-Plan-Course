function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function collapseSpaces(s: string): string {
  return s
    .split(/\s+/)
    .filter(Boolean)
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function localizeFoodTitleToRu(text: string): string {
  const orig = String(text ?? '').trim();
  if (!orig) return orig;
  if (!/[a-z]/i.test(orig)) return orig;

  let s = orig.toLowerCase();

  for (const [en, ru] of PHRASES) {
    if (!ru) continue;
    s = s.replace(new RegExp(escapeRe(en), 'gi'), ru);
  }

  s = s.replace(/\b([a-z]+)\b/gi, (word) => {
    const w = word.toLowerCase();
    if (WORDS[w] !== undefined) return WORDS[w] || '';
    return word;
  });

  s = collapseSpaces(s);
  if (!s) return orig;

  const cap = s.charAt(0).toUpperCase() + s.slice(1);
  return cap;
}

export function localizeProductIngredientsRu(ingredients: ProductIngredient[]): ProductIngredient[] {
  return ingredients.map((row) => ({
    name: localizeFoodTitleToRu(String(row?.name ?? '')),
    grams: Number(row?.grams) || 0,
  }));
}

export function localizeProductFields(name: string, ingredients: ProductIngredient[]): {
  name: string;
  ingredients: ProductIngredient[];
} {
  const rawName = String(name ?? '').trim();
  const stripPortion = rawName.replace(/\s·[SML]$/i, '').trim();
  const localizedBase = localizeFoodTitleToRu(stripPortion);
  const portion = /·[SML]$/i.test(rawName) ? rawName.match(/\s(·[SML])$/i)?.[1] ?? '' : '';
  const newName = portion ? `${localizedBase} ${portion}` : localizedBase;
  return {
    name: newName,
    ingredients: localizeProductIngredientsRu(Array.isArray(ingredients) ? ingredients : []),
  };
}
