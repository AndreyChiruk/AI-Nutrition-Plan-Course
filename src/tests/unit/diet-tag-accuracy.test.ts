import { assert } from 'chai';
import { describe, it } from 'mocha';
import { DIET_FORBIDDEN_INGREDIENTS } from '../../meal-plan/slovari';
import { containsDietKey } from '../../meal-plan/dietary-rules';

/**
 * Точность диетических тегов.
 *
 * ─── Что было не так ────────────────────────────────────────────────────
 *
 * 1. В списках запрещённых отсутствовали целые группы продуктов:
 *    мясные деликатесы (чоризо, хамон, прошутто, карбонад, грудинка),
 *    виды рыбы (сельдь, скумбрия, палтус) и названия сыров (пармезан,
 *    моцарелла, фета). Из-за этого «Сельдь в масле» и «Рагу с чоризо»
 *    получали тег vegan, а «Риболлита» с пармезаном — ни одного тега.
 *
 * 2. Добавление основы «сельд» для сельди дало ложное срабатывание
 *    на «сельдерей» — овощ. Понадобились точные формы «сельдь», «селедк».
 *
 * 3. В `backfill-catalog-tags.ts` проверки `hasAnimal` и `dairy` шли
 *    через СВОИ регулярные выражения со словами «сыр», «молок». Названия
 *    конкретных сыров не содержат подстроку «сыр», поэтому пармезан
 *    не распознавался как молочный продукт.
 */
const vegan = DIET_FORBIDDEN_INGREDIENTS.vegan ?? [];
const vegetarian = DIET_FORBIDDEN_INGREDIENTS.vegetarian ?? [];

/** Запрещено ли вегану (по общему словарю). */
function forbiddenForVegan(text: string): boolean {
  return vegan.some((key) => containsDietKey(text, key));
}

/** Запрещено ли вегетарианцу. */
function forbiddenForVegetarian(text: string): boolean {
  return vegetarian.some((key) => containsDietKey(text, key));
}

describe('диетические теги: мясные деликатесы', () => {
  it('распознаёт колбасные изделия и деликатесы', () => {
    for (const product of ['чоризо', 'хамон', 'прошутто', 'пепперони', 'салями', 'карбонад', 'буженина', 'грудинка', 'окорок']) {
      assert.isTrue(forbiddenForVegan(product), `«${product}» должно быть запрещено вегану`);
    }
  });

  it('распознаёт английские названия', () => {
    for (const product of ['chorizo', 'ham', 'prosciutto', 'pepperoni', 'salami', 'brisket']) {
      assert.isTrue(forbiddenForVegan(product), `«${product}» должно быть запрещено`);
    }
  });

  it('реальный случай: «Сельдь в масле» больше не веганская', () => {
    const hay = 'сельдь | лук | оливковое масло | перец | лавровый лист';
    assert.isTrue(forbiddenForVegan(hay));
  });

  it('реальный случай: «Рагу из нута с чоризо» не веганское', () => {
    const hay = 'оливковое масло | лук | морковь | чеснок | чоризо | нут | шпинат';
    assert.isTrue(forbiddenForVegan(hay));
  });
});

describe('диетические теги: рыба и морепродукты', () => {
  it('распознаёт виды рыбы, которых не было в списке', () => {
    for (const fish of ['сельдь', 'селедка', 'скумбрия', 'палтус', 'камбала', 'карп', 'щука', 'окунь', 'судак', 'хек']) {
      assert.isTrue(forbiddenForVegan(fish), `«${fish}» должно быть запрещено`);
    }
  });

  it('НЕ путает сельдь с сельдереем (овощ)', () => {
    // Основа «сельд» давала ложное срабатывание на «сельдерей»,
    // из-за чего «Риболлита» с сельдереем теряла теги.
    assert.isFalse(forbiddenForVegan('сельдерей'), 'сельдерей — овощ, разрешён вегану');
    assert.isFalse(forbiddenForVegan('сельдерей стебель'));
    assert.isTrue(forbiddenForVegan('сельдь'), 'сельдь — рыба, запрещена');
    assert.isTrue(forbiddenForVegan('селедка'));
  });
});

describe('диетические теги: молочные продукты', () => {
  it('распознаёт названия сыров', () => {
    // Основа «сыр» ищется с начала слова, поэтому «Пармезан» не находился.
    for (const cheese of ['пармезан', 'моцарелла', 'фета', 'брынза', 'рикотта', 'маскарпоне', 'чеддер', 'гауда']) {
      assert.isTrue(forbiddenForVegan(cheese), `«${cheese}» — молочный продукт`);
    }
  });

  it('реальный случай: «Риболлита» с пармезаном не веганская', () => {
    const hay = 'помидоры | розмарин | кейл | хлеб | лук | пармезан';
    assert.isTrue(forbiddenForVegan(hay), 'пармезан делает блюдо невеганским');
    assert.isFalse(forbiddenForVegetarian(hay), 'но вегетарианским остаётся');
  });
});

describe('диетические теги: растительные продукты не задеты', () => {
  it('овощи, крупы и бобовые разрешены вегану', () => {
    for (const plant of ['нут', 'чечевица', 'шпинат', 'кейл', 'тофу', 'гречка', 'морковь', 'сельдерей', 'помидор', 'кабачок']) {
      assert.isFalse(forbiddenForVegan(plant), `«${plant}» должно быть разрешено вегану`);
    }
  });

  it('реальный случай: «Винегрет» остаётся веганским', () => {
    const hay = 'свёкла | картофель | морковь | огурцы солёные | горошек | лук | масло растительное';
    assert.isFalse(forbiddenForVegan(hay));
  });

  it('реальный случай: «Лобио из фасоли» остаётся веганским', () => {
    const hay = 'фасоль | лук | грецкие орехи | чеснок | кинза | масло растительное';
    assert.isFalse(forbiddenForVegan(hay));
  });
});
