import { assert } from 'chai';
import { describe, it } from 'mocha';

/**
 * Тесты простановки диетических тегов по составу блюда.
 *
 * Аудит каталога выявил 11 нарушений: блюда с мясом, рыбой и желатином
 * были помечены `vegetarian` (и даже `vegan`). Причины:
 *   1. Список мяса не покрывал «мясо», «сардин», «донер», «фрикадельки» и др.
 *      → «Капсалон» с составом «Мясо донер» получал тег vegetarian.
 *   2. Желатин считался допустимым для вегетарианцев, хотя делается
 *      из костей и хрящей → «Мусс из малины» с «Листья желатина» получал
 *      тег vegetarian.
 *   3. Морепродукты покрывались неполно → «Свежие сардины» получали `vegan`.
 */
const MEAT =
  /(козлятин|мяс|куриц|курин|говяд|свинин|баранин|индейк|телятин|теляч|утк|утин|гус|кролик|бекон|ветчин|колбас|сосиск|сардел|фарш|фрикадел|тефтел|донер|шаурм|шаверм|хамон|салями|паштет|печень|ливер|субпродукт|ребрышк|корейк|шницель|эскалоп|буженин|карбонад|ростбиф|рыб|лосос|семг|форел|треск|тунец|тунц|сельд|скумбр|сардин|анчоус|сайд|палтус|хек|камбал|минтай|икр|кревет|миди|кальмар|краб|лобстер|осьминог|устриц|гребеш|морепродукт|лангуст)/;
const ANIMAL_NON_MEAT = /(молок|сыр|творог|йогурт|кефир|сметан|сливк|масло сливочн|яйц|мёд|мед(?![а-яё])|медов)/;
const NON_VEG_ADDITIVE = /(желатин|сычуж|кармин|шеллак)/;

function detectTags(ingredients: string[]): string[] {
  const hay = ingredients.join(' | ').toLowerCase();
  const hasMeat = MEAT.test(hay);
  const hasAnimal = ANIMAL_NON_MEAT.test(hay);
  const hasAdditive = NON_VEG_ADDITIVE.test(hay);
  const tags: string[] = [];
  if (!hasMeat && !hasAnimal && !hasAdditive) tags.push('vegan');
  if (!hasMeat && !hasAdditive) tags.push('vegetarian');
  return tags;
}

describe('диетические теги: вегетарианство', () => {
  it('блюдо с «Мясо донер» не является вегетарианским (главный кейс)', () => {
    const tags = detectTags(['Картофель фри', 'Мясо донер', 'Чесночный соус', 'Салат']);
    assert.notInclude(tags, 'vegetarian');
    assert.notInclude(tags, 'vegan');
  });

  it('рыба не является вегетарианской и тем более веганской', () => {
    for (const fish of ['Сардины', 'Лосось', 'Треска', 'Сельдь', 'Скумбрия', 'Тунец']) {
      const tags = detectTags([fish, 'Масло растительное', 'Соль']);
      assert.notInclude(tags, 'vegetarian', fish);
      assert.notInclude(tags, 'vegan', fish);
    }
  });

  it('желатин делает блюдо невегетарианским', () => {
    const tags = detectTags(['Листья желатина', 'Малина', 'Сахарная пудра']);
    assert.notInclude(tags, 'vegetarian', 'желатин делают из костей и хрящей');
    assert.notInclude(tags, 'vegan');
  });

  it('мясные субпродукты и колбасы исключаются', () => {
    for (const item of ['Печень', 'Ливер', 'Колбаса', 'Сосиски', 'Бекон', 'Ветчина', 'Фарш']) {
      assert.notInclude(detectTags([item]).join(','), 'vegetarian', item);
    }
  });

  it('морепродукты исключаются', () => {
    for (const item of ['Креветки', 'Мидии', 'Кальмар', 'Краб', 'Осьминог']) {
      assert.notInclude(detectTags([item]).join(','), 'vegetarian', item);
    }
  });

  it('настоящие вегетарианские блюда сохраняют тег', () => {
    for (const dish of [
      ['Помидор', 'Огурец', 'Масло оливковое'],
      ['Картофель', 'Морковь', 'Лук'],
      ['Рис', 'Брокколи'],
    ]) {
      assert.include(detectTags(dish).join(','), 'vegetarian', dish.join('+'));
    }
  });

  it('козий сыр — вегетарианский продукт, а не мясо', () => {
    // Регресс: в справочнике DIET_FORBIDDEN_INGREDIENTS корни «козий»/«козл»
    // помечали как невегетарианские блюда с КОЗЬИМ СЫРОМ, хотя это молочный
    // продукт. Затронуто было 3 блюда: «Запечённый баклажан с козьим сыром»,
    // «Салат из баклажанов с кускусом» и др.
    const tags = detectTags(['Баклажан', 'Козий сыр', 'Помидоры черри', 'Мята']);
    assert.include(tags, 'vegetarian', 'козий сыр не делает блюдо невегетарианским');
  });

  it('козлятина всё же не является вегетарианской', () => {
    const tags = detectTags(['Козлятина', 'Помидоры', 'Лук']);
    assert.notInclude(tags, 'vegetarian', 'козлятина — это мясо');
  });

  it('блюдо с молоком и яйцами — вегетарианское, но не веганское', () => {
    const tags = detectTags(['Молоко', 'Яйца', 'Мука']);
    assert.include(tags, 'vegetarian');
    assert.notInclude(tags, 'vegan');
  });
});
