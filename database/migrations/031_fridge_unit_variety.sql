-- Восстановление единиц измерения в холодильнике.
--
-- Причина: normalizeMassUnit в users.service пропускал только «г» и «кг»,
-- а всё остальное молча превращал в «г». Пользователь выбирал «мл» для
-- молока или «шт» для яиц, но в базе и в списке оказывались граммы.
-- Миграция 013 закрепила это поведение, переписав вообще все единицы в «г».
--
-- Код уже исправлен: теперь сохраняются г, кг, мл, л и шт. Здесь
-- восстанавливаем разумную единицу для строк, которые пострадали ранее.

-- Жидкости: если записано в граммах, считаем граммы миллилитрами —
-- плотность воды близка к 1, а «мл» для напитка понятнее пользователя.
--
-- Важно: в Postgres `\b` не работает с кириллицей (проверено:
-- 'Яйцо' ~ '\bяйц' → false), поэтому границы слова задаём явно,
-- а для слов в начале строки полагаемся на `^`.
UPDATE fridge_items
SET unit = 'мл'
WHERE lower(trim(coalesce(unit, 'г'))) = 'г'
  AND lower(name) ~ '(молок|кефир|ряженк|сок|вода|чай|кофе|компот|бульон|напит|сироп|уксус|вино|пиво|сливк|йогурт)';

-- Только большие объёмы показываем в литрах.
-- Порог 5000 мл: 1000 мл молока естественнее выглядит как «1000 мл»,
-- а 5 литров воды — как «5 л». Значение в литрах пересчитываем,
-- иначе «5000 л» было бы бессмыслицей.
UPDATE fridge_items
SET unit = 'л',
    quantity = round((quantity / 1000.0)::numeric, 3)::double precision
WHERE unit = 'мл'
  AND quantity >= 5000;

-- Штучные продукты: яйца, фрукты, овощи, хлеб.
-- Границы слова заданы явно, потому что `\b` кириллицу не понимает.
UPDATE fridge_items
SET unit = 'шт'
WHERE lower(trim(coalesce(unit, 'г'))) = 'г'
  AND lower(name) ~ '(^|[^а-яё])(яйц|яблок|банан|апельсин|мандарин|груш|лимон|лайм|киви|авокадо|томат|помидор|огурец|перец|лук|морков|картоф|кабачок|баклажан|свекл|капуст|редис|виноград|слив|персик|абрикос|вишн|черешн|гранат|манго|ананас|хлеб|батон|булочк|лаваш|зубчик)';

-- Значение по умолчанию оставляем «г»: это безопасный вариант для
-- неизвестного продукта, а конкретную единицу теперь задаёт код.
ALTER TABLE fridge_items
  ALTER COLUMN unit SET DEFAULT 'г';
