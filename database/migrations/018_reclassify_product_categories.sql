-- 018_reclassify_product_categories.sql
--
-- Причина: прежняя логика импорта каталога (mealSlotByApiCategory +
-- inferMealSlotFromDishName) отправляла в `dinner` всё, что не совпало с узким
-- списком ключевых слов. В результате в `products` оказалось:
--     dinner = 406, snack = 241, breakfast = 22, lunch = 0
--
-- Генератор планов грузит пулы строго по `category`, поэтому пул `lunch` был
-- всегда пуст: обед подставлялся из ужинов/закусок, а `refineProductsToTarget`
-- не мог подобрать его по калориям. Категория в снапшоте перезаписывалась
-- слотом, из-за чего внешне это выглядело корректно.
--
-- Этот скрипт переклассифицирует существующие блюда по названию.
-- Идемпотентен: обновляет только строки, где категория расходится с названием.
-- Приложение делает то же самое при старте (PlansLibrarySeedService), но SQL
-- полезен для чистой БД и для применения миграций без запуска API.

-- Супы и горячее с гарниром -> обед
UPDATE products SET category = 'lunch'
WHERE category <> 'lunch'
  AND (
    name ~* '(суп|борщ|бульон|солянк|похлеб|уха|окрошк|харчо|гаспачо|боул|плов|булгур|кускус|полба|перловк|ячнев|гречк|рис |рис$|лапша|паста|спагетти|макарон|ризотто|лазань|карри|гуляш|рагу|фрикадель|тефтел|котлет|шницель|эскалоп|бефстроганов|пожарск|жаркое|тушен|чахохбил|сациви|аджапсандал|мусака|паэлья|кесадиль|кесадиль|суши|пельмен|вареник|манты|хинкал|чебурек|ригатони|пенне|фарфалле|тортеллини|равиоли|курин|куриц|куриная|говядин|говяж|свинин|свиная|индейк|баранин|телятин|ягнен|лосос|треск|тунец|рыба|кревет|миди|кальмар|стейк|филе|ветчин|утк|кролик|тофу|бургер|пицц|сэндвич|шаурм|шаверм|д[её]нер|кебаб|запеканк|картофельное пюре)'
  )
  AND name !~* '^(салат|торт|печенье|пирожн|кекс|маффин|брауни|десерт)';

-- Завтраки
UPDATE products SET category = 'breakfast'
WHERE category <> 'breakfast'
  AND name ~* '(завтрак|каша|овсян|овсяноблин|блин|блинчик|оладь|омлет|яичниц|гренк|тост|сырник|вафл|круассан|шакшук|драник|пудинг рисов|йогурт с|манн(ая|ой) каш|ленив(ые|ых) вареник)';

-- Перекусы: десерты, напитки, выпечка, фрукты, орехи, лёгкие закуски
UPDATE products SET category = 'snack'
WHERE category <> 'snack'
  AND name ~* '(салат|смузи|перекус|десерт|торт|пирожн|печенье|кекс|маффин|брауни|пончик|пудинг|мусс|желе|мороженое|сорбет|конфет|шоколад|козинак|халва|нуга|мармелад|зефир|пастил|варенье|джем|йогурт|мусли|гранола|чипсы|сухарик|крекер|орешк|миндал|фундук|кешью|фисташк|арахис|семечк|батончик|компот|чай|кофе|какао|лимонад|морс|кисель|квас|фрукт|ягод|банан|яблоко|груш|апельсин|мандарин|виноград|арбуз|дын|персик|абрикос|слив|вишн|черешн|клубник|малин|черник|голубик|смородин|крыжовник|инжир|финик|изюм|кураг|чернослив|баклава|крамбл)';

-- Ужины: овощные и запечённые блюда
UPDATE products SET category = 'dinner'
WHERE category <> 'dinner'
  AND name ~* '(ужин|запечен|запеч[её]н|тушен|овощ|баклажан|кабачок|цукини|брокколи|цветная капуст|спарж|шпинат|тыкв|свекл|морков|репа|редьк|редис|сельдерей|фенхел|артишок|темпе|гриб|шампиньон|вешенк)';

-- Индекс для выборки пулов по категории (используется генератором планов)
CREATE INDEX IF NOT EXISTS products_category_idx ON products(category);

-- Диагностика: после миграции ни одна категория не должна быть пустой.
DO $$
DECLARE
  b int; l int; d int; s int;
BEGIN
  SELECT count(*) INTO b FROM products WHERE category = 'breakfast';
  SELECT count(*) INTO l FROM products WHERE category = 'lunch';
  SELECT count(*) INTO d FROM products WHERE category = 'dinner';
  SELECT count(*) INTO s FROM products WHERE category = 'snack';
  RAISE NOTICE 'Категории после переклассификации: breakfast=%, lunch=%, dinner=%, snack=%', b, l, d, s;
  IF l = 0 OR b = 0 OR d = 0 OR s = 0 THEN
    RAISE WARNING 'Одна из категорий products пуста — генератор планов подставит заглушки. Запустите seed каталога.';
  END IF;
END $$;
