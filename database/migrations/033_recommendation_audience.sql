-- Аудитория базовых рекомендаций: вместо 'all' — 'adult' / 'minor'.
--
-- Раньше поле audience было свободным текстом со значением 'all'
-- по умолчанию, и в админке его приходилось вводить вручную. Теперь
-- в интерфейсе два варианта: «Старше 18» (adult) и «Младше 18» (minor).
--
-- Поле нигде не участвует в логике подбора — только отображается
-- в таблице админки. Миграция нужна, чтобы у существующих записей
-- в выпадающем списке было выбранное значение, а не пусто.
--
-- 'all' означало «рекомендация для всех»; переводим в 'adult' —
-- базовые советы по питанию адресованы взрослым пользователям.

UPDATE base_recommendations
SET audience = 'adult'
WHERE audience IS NULL OR audience = 'all';

-- Значение по умолчанию для новых записей.
ALTER TABLE base_recommendations
  ALTER COLUMN audience SET DEFAULT 'adult';
